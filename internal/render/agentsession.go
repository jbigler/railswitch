package render

import (
	"fmt"
	"slices"
)

// AgentTmux runs tmux on a service agent's session server: its own socket,
// apart from any tmux the agent itself runs. The one place core names the
// multiplexer (TestGenericity).
var AgentTmux = []string{"tmux", "-L", "agent"}

// AgentClientTERM is a session client's TERM: the terminal's own can be one
// the container has no terminfo for.
const AgentClientTERM = "TERM=xterm-256color"

// A service agent's container is the agent's environment (D142): up starts
// it and its main process is a tmux server with no session; the agent runs
// in the tmux session AgentSession, which railswitch agent creates (the
// package's entrypoint, then its exec words or the user's arguments) or
// attaches to, from any number of terminals at once.
const (
	// AgentSession is the agent's session on that server.
	AgentSession = "agent"
	// AgentTmuxConf is the server's configuration in the container.
	AgentTmuxConf = "/usr/local/share/railswitch/agent-tmux.conf"
	agentTmuxRel  = ".railswitch/hooks/agent-tmux.conf"
	agentTmuxText = `# railswitch's agent session server (D142). Generated by railswitch.
# No prefix key: the agent gets every key but Ctrl-\, which detaches this
# terminal (the agent keeps running); closing the terminal also leaves.
set -g prefix None
set -g prefix2 None
unbind-key -a
unbind-key -a -T root
bind-key -T root 'C-\' detach-client
set -g status off
# The wheel scrolls back through the agent's output (shift selects text);
# no other mouse binding (tmux's right-click menu can kill the agent).
set -g mouse on
bind-key -T root WheelUpPane if-shell -F '#{||:#{pane_in_mode},#{mouse_any_flag}}' 'send-keys -M' 'copy-mode -e'
bind-key -T root WheelDownPane send-keys -M
set -g history-limit 50000
set -g escape-time 0
set -g default-terminal tmux-256color
set -as terminal-features ',xterm-256color:RGB'
# Shift+Enter (a new line, not a submit) reaches the agent as an extended
# key instead of a plain Enter, from a host terminal or the dashboard's.
set -s extended-keys on
set -as terminal-features 'xterm*:extkeys'
# Viewers of different sizes: the window follows whoever typed last.
set -g window-size latest
set -g aggressive-resize on
`
)

// AgentSessionCmd is a service agent's command: its package's entrypoint
// ("" for none) and the exec words a session runs it with by default.
type AgentSessionCmd struct {
	Entrypoint string
	Exec       []string
}

// agentSession makes service agent s's unit run the session server: its
// agent command moves to s.Session. The image's own ENTRYPOINT can't run in
// a session, so an agent without an entrypoint needs exec words.
func (b *builder) agentSession(s *Service, agent string) error {
	if s.Entrypoint == "" && len(s.Exec) == 0 {
		return fmt.Errorf("[agents.%s] run = \"service\": the agent's package has no entrypoint or [unit] exec for its session to run", agent)
	}
	s.Session = &AgentSessionCmd{Entrypoint: s.Entrypoint, Exec: s.Exec}
	s.Entrypoint = AgentTmux[0]
	s.Exec = append(slices.Clone(AgentTmux[1:]), "-f", AgentTmuxConf, "-D")
	if !b.assets[agentTmuxRel] {
		b.assets[agentTmuxRel] = true
		b.m.Assets = append(b.m.Assets, Asset{Rel: agentTmuxRel, Data: []byte(agentTmuxText), Mode: 0o644})
	}
	s.Mounts = append(s.Mounts, Mount{Source: literal(b.ws(agentTmuxRel)), Target: AgentTmuxConf, Options: "ro,z"})
	return nil
}
