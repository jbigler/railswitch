package render

import (
	"crypto/sha256"
	"fmt"
	"strings"
)

// agentSetupPath is an agent's entrypoint when its [agents.<name>] setup
// is set (D133): it runs the setup once per agent home, then execs the
// package's entrypoint with the agent's arguments (which `railswitch agent
// -- …` may replace, so the entrypoint is named in the script, not passed).
const agentSetupPath = "/usr/local/bin/railswitch-agent-setup"

// agentSetupScript runs cmds in the agent's home once: a marker per
// command that succeeded (<home>/.railswitch-setup.d/<hash of it>) skips
// it at the next start, and one named for the whole list's hash
// (<home>/.railswitch-setup-<hash>) skips the list once all of it ran. So
// a run that stopped at a failing command goes on from that command,
// never again through the ones before it, which may not run twice
// (gh extension install refuses an installed extension); a changed
// command runs again. Each command runs in its own `sh -ec` in dir, in
// order, with no stdin (the agent's terminal stays the agent's); the
// first to fail stops the rest and is reported with its exit status, and
// the agent starts all the same (the next start tries it again). It execs
// entrypoint, the package's, with the arguments.
func agentSetupScript(agent string, cmds []string, dir, home, entrypoint string) []byte {
	sum := sha256.Sum256([]byte(strings.Join(cmds, "\x00")))
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by railswitch from project.toml [agents." + agent + "] setup (D133).\n")
	fmt.Fprintf(&b, "marker=%s/.railswitch-setup-%x\n", shQuote(home), sum[:8])
	fmt.Fprintf(&b, "done=%s/.railswitch-setup.d\n", shQuote(home))
	// A function, not a set -e subshell in an if: set -e is ignored there,
	// so a failing command would not stop the rest or the marker.
	b.WriteString("railswitch_setup() {\n  mkdir -p \"$done\" || return 1\n")
	for _, c := range cmds {
		q := shQuote(c)
		one := sha256.Sum256([]byte(c))
		fmt.Fprintf(&b, "  if [ ! -e \"$done/%x\" ]; then\n", one[:8])
		b.WriteString("    printf 'setup " + agent + ": %s\\n' " + q + "\n")
		b.WriteString("    if (cd " + shQuote(dir) + " && exec sh -ec " + q + ") </dev/null; then\n")
		fmt.Fprintf(&b, "      : > \"$done/%x\"\n", one[:8])
		b.WriteString("    else\n      printf 'setup " + agent + ": exit %d: %s\\n' \"$?\" " + q + " >&2\n      return 1\n    fi\n  fi\n")
	}
	b.WriteString("}\nif [ ! -e \"$marker\" ]; then\n  if railswitch_setup; then\n    : > \"$marker\"\n  else\n    printf 'setup " + agent + ": failed; it runs again at the next start, from the command that failed\\n' >&2\n  fi\nfi\n")
	b.WriteString("exec " + shQuote(entrypoint) + " \"$@\"\n")
	return []byte(b.String())
}

// agentSetup puts agent's setup script in front of s's entrypoint. An
// agent package with no entrypoint can't have one: its image's own
// ENTRYPOINT and CMD would be lost behind the script.
func (b *builder) agentSetup(s *Service, agent string, cmds []string) error {
	if len(cmds) == 0 {
		return nil
	}
	if s.Entrypoint == "" {
		return fmt.Errorf("[agents.%s] setup: the agent's package has no entrypoint to run after it", agent)
	}
	script := agentSetupScript(agent, cmds, hookDir, appHome, s.Entrypoint)
	s.Entrypoint = agentSetupPath
	b.hookAsset(s, ".railswitch/hooks/agent-"+agent+"-setup.sh", agentSetupPath, script)
	return nil
}
