package render

import (
	"crypto/sha256"
	"fmt"
	"strings"
)

// agentSetupPath is an agent's entrypoint when its [agents.<name>] setup
// is set (D133): it runs the setup once per agent home, then execs the
// package's entrypoint with the agent's arguments (which `railswitch agent
// -- …` may replace, so the entrypoint is named in the script, not passed).
const agentSetupPath = "/usr/local/bin/railswitch-agent-setup"

// agentSetupScript runs cmds in the agent's home once: a marker named for
// the list's hash (<home>/.railswitch-setup-<hash>) records a run in which
// every command succeeded, so a changed list runs again. Each command runs
// in its own `sh -ec` in dir, in order, with no stdin (the agent's
// terminal stays the agent's); the first to fail stops the rest and is
// reported, and the agent starts all the same (the next start tries
// again). It execs entrypoint, the package's, with the arguments.
func agentSetupScript(agent string, cmds []string, dir, home, entrypoint string) []byte {
	sum := sha256.Sum256([]byte(strings.Join(cmds, "\x00")))
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by railswitch from project.toml [agents." + agent + "] setup (D133).\n")
	fmt.Fprintf(&b, "marker=%s/.railswitch-setup-%x\n", shQuote(home), sum[:8])
	// A function, not a set -e subshell in an if: set -e is ignored there,
	// so a failing command would not stop the rest or the marker.
	b.WriteString("railswitch_setup() {\n")
	for _, c := range cmds {
		q := shQuote(c)
		b.WriteString("  printf 'setup " + agent + ": %s\\n' " + q + "\n")
		b.WriteString("  (cd " + shQuote(dir) + " && exec sh -ec " + q + ") </dev/null || return 1\n")
	}
	b.WriteString("}\nif [ ! -e \"$marker\" ]; then\n  if railswitch_setup; then\n    : > \"$marker\"\n  else\n    printf 'setup " + agent + ": failed; it runs again at the next start\\n' >&2\n  fi\nfi\n")
	b.WriteString("exec " + shQuote(entrypoint) + " \"$@\"\n")
	return []byte(b.String())
}

// agentSetup puts agent's setup script in front of s's entrypoint. An
// agent package with no entrypoint can't have one: its image's own
// ENTRYPOINT and CMD would be lost behind the script.
func (b *builder) agentSetup(s *Service, agent string, cmds []string) error {
	if len(cmds) == 0 {
		return nil
	}
	if s.Entrypoint == "" {
		return fmt.Errorf("[agents.%s] setup: the agent's package has no entrypoint to run after it", agent)
	}
	script := agentSetupScript(agent, cmds, hookDir, appHome, s.Entrypoint)
	s.Entrypoint = agentSetupPath
	b.hookAsset(s, ".railswitch/hooks/agent-"+agent+"-setup.sh", agentSetupPath, script)
	return nil
}
