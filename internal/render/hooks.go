package render

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
)

// Hook scripts (D126): render writes one per [hooks] list that runs as a
// unit starts, mounts it read-only and puts it in front of the service's
// own command. Each hook runs in its own `sh -ec`, so a hook's `cd` or
// `exit 0` ends only that hook; a failing hook fails the start.
const (
	startHookRel = ".railswitch/hooks/start.sh"
	depsHookRel  = ".railswitch/hooks/deps.sh"
	// StartHookPath runs the start hooks, then execs its arguments (the
	// app's server), as the pack's entrypoint execs it.
	StartHookPath = "/usr/local/bin/railswitch-start"
	// DepsHookPath is deps's entrypoint: it runs its arguments (the pack's
	// deps entrypoint and command), then the deps hooks.
	DepsHookPath = "/usr/local/bin/railswitch-deps"
)

// hookDir is where every hook runs: the worktree.
const hookDir = "/app"

// hookScript is the script for cmds, each run in dir; before runs them
// before exec "$@", else after "$@".
func hookScript(list string, cmds []string, before bool, dir string) []byte {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by railswitch from project.toml [hooks] " + list + " (D126).\n# Each hook runs in its own shell in " + dir + ".\nset -e\n")
	if !before {
		b.WriteString("if [ \"$#\" -gt 0 ]; then \"$@\"; fi\n")
	}
	for _, c := range cmds {
		q := shQuote(c)
		b.WriteString("printf 'hook " + list + ": %s\\n' " + q + "\n")
		b.WriteString("(cd " + shQuote(dir) + " && exec sh -ec " + q + ")\n")
	}
	if before {
		b.WriteString("exec \"$@\"\n")
	}
	return []byte(b.String())
}

// shQuote is s as one single-quoted sh word.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// hooks wires the project's start hooks into app and its deps hooks into
// deps.
func (b *builder) hooks(app, deps *Service) error {
	h := b.in.Project.Hooks
	if len(h.Create) > 0 && app.Health == nil {
		// Only a health check tells up the app is ready for them.
		return errors.New("[hooks] create need the app's health check: up runs them once it passes, and the app has none ([services." + app.ID + "] health)")
	}
	if len(h.Start) > 0 {
		switch {
		case len(app.Exec) > 0:
			app.Exec = append([]string{StartHookPath}, app.Exec...)
		case app.Command != "":
			app.Command = StartHookPath + " " + app.Command
		default:
			return errors.New("[hooks] start: the app has no command to run after them (the pack's [app] server)")
		}
		b.hookAsset(app, startHookRel, StartHookPath, hookScript("start", h.Start, true, hookDir))
	}
	if len(h.Deps) > 0 {
		if deps.Entrypoint != "" {
			deps.Command = strings.TrimSpace(deps.Entrypoint + " " + deps.Command)
		}
		deps.Entrypoint = DepsHookPath
		script := hookScript("deps", h.Deps, false, hookDir)
		b.hookAsset(deps, depsHookRel, DepsHookPath, script)
		app.HookScripts = append(app.HookScripts, script)
	}
	return nil
}

func (b *builder) hookAsset(s *Service, rel, target string, data []byte) {
	s.HookScripts = append(s.HookScripts, data)
	b.m.Assets = append(b.m.Assets, Asset{Rel: rel, Data: data, Mode: 0o755})
	s.Mounts = append(s.Mounts, Mount{Source: literal(b.ws(rel)), Target: target, Options: "ro,z"})
}

// CreatePending is the marker of a worktree whose [hooks] create haven't
// all run yet: written (empty) when the worktree is added; up records each
// command that succeeds in it, one per line, and removes it when all have
// (or there are none). A worktree from before has none and never runs them.
func CreatePending(ws, slug string) string {
	return filepath.Join(ws, ".railswitch", "create-pending", slug)
}

// MarkCreatePending writes slug's CreatePending marker.
func MarkCreatePending(ws, slug string) error {
	p := CreatePending(ws, slug)
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return err
	}
	return os.WriteFile(p, nil, 0o600)
}
