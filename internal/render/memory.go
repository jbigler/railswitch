// Shared agent memory (D136): with [memory], one Dolt SQL server per
// project holds the beads (bd) store every agent of every worktree uses as
// a client. The server and the agents meet on the project's memory network,
// which nothing else joins: internal (no route out), so the server needs
// no firewall, and the agents' firewall hook allows it as one of their own
// networks.
const (
	// MemoryImage is the Dolt server: the version beads pins
	// (beads docs/architecture/dolt.md, "2.2.0"; 2.3.0 and 2.3.1 regress).
	MemoryImage = "docker.io/dolthub/dolt-sql-server:2.2.0"
	// MemoryHost is the server's alias on the memory network.
	MemoryHost = "memory"
	// MemoryPort is the image's SQL port.
	MemoryPort = 3306
	// MemoryDatabase is the beads database on the server.
	MemoryDatabase = "beads"
	// MemoryDir holds what render writes for memory: beads/ (the agents'
	// BEADS_DIR, 0700) and railswitch-prime.sh.
	MemoryDir = ".railswitch/memory"
	// MemoryBeadsDir is where an agent sees MemoryDir/beads: inside its
	// home, as bd writes a lock beside BEADS_DIR.
	MemoryBeadsDir = appHome + "/.railswitch-memory/beads"
	// MemoryPrime is railswitch-prime in an agent: the project's guidance
	// and the label convention, then `bd prime`.
	MemoryPrime = "/usr/local/bin/railswitch-prime"
)

// memoryMetadata is beads' metadata.json for a server-mode client
// (beads configfile.go; what `bd init --server --database beads` writes,
// less the project_id it adopts from the database).
const memoryMetadata = `{
  "database": "dolt",
  "backend": "dolt",
  "dolt_mode": "server",
  "dolt_database": "` + MemoryDatabase + `"
}
`

// memoryConfig is beads' config.yaml: no-git-ops is what `bd init
// --stealth` sets, so bd never runs git; events-journal records every
// write in bd_events_journal, which `railswitch memory --since` reads.
const memoryConfig = "# Generated by railswitch from project.toml [memory] (D136).\nno-git-ops: true\nevents-journal: true\n"

// MemoryEnv is what an agent of a [memory] project gets (beads
// configfile.go, main.go, metrics: see handoff/shared-memory/BEADS.md),
// actor its BEADS_ACTOR.
func MemoryEnv(actor string) map[string]string {
	return map[string]string{
		"BEADS_DIR":                  MemoryBeadsDir,
		"BEADS_DOLT_SERVER_MODE":     "1", // never a local server of its own
		"BEADS_DOLT_AUTO_START":      "0",
		"BEADS_DOLT_SERVER_HOST":     MemoryHost,
		"BEADS_DOLT_SERVER_PORT":     strconv.Itoa(MemoryPort),
		"BEADS_DOLT_SERVER_USER":     "root",
		"BEADS_DOLT_SERVER_DATABASE": MemoryDatabase,
		"BEADS_ACTOR":                actor,
		"BD_DISABLE_METRICS":         "1", // on by default, to gastownhall-eventsapi.com
		"BD_EVENTS_JOURNAL":          "1", // only writers that have it are journaled
	}
}

// memoryRule is what every agent is told about its own memory (D146):
// the agent's home, and any memory its tool keeps there, is the
// worktree's, and goes with it.
const memoryRule = "Keep what you learn in this store, never in your own tool's memory files (MEMORY.md, a memory folder): those stay in this worktree and are deleted with it, and no other agent sees them. Before you store, search with bd memories <word> and update an existing key (bd remember --key <key> \"<text>\") instead of adding another; one fact per memory."

// memoryPrimeScript prints guidance, the worktree label convention and
// memoryRule, then runs `bd prime` with the script's arguments.
func memoryPrimeScript(guidance string) []byte {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by railswitch from project.toml [memory] (D136).\n")
	b.WriteString("printf '%s\\n' '# Shared memory (railswitch)' '' " + shQuote("Every agent of this project, in every worktree, reads and writes this beads store (bd).") + " ''\n")
	b.WriteString("printf '%s\\n' " + shQuote(guidance) + " ''\n")
	b.WriteString("printf 'You work in worktree %s. Label every issue you create with worktree:%s (bd create -l worktree:%s); see your worktree'\\''s work with bd ready -l worktree:%s.\\n\\n' \"$WORKTREE_SLUG\" \"$WORKTREE_SLUG\" \"$WORKTREE_SLUG\" \"$WORKTREE_SLUG\"\n")
	b.WriteString("printf '%s\\n' " + shQuote(memoryRule) + " ''\n")
	b.WriteString("exec bd prime \"$@\"\n")
	return []byte(b.String())
}

// memoryAgent gives agent service s BEADS_DIR and railswitch-prime (its
// network and env: services and envSpecs).
func (b *builder) memoryAgent(s *Service) {
	mem := b.in.Project.Memory
	if mem == nil {
		return
	}
	for _, f := range []struct{ name, data string }{{"metadata.json", memoryMetadata}, {"config.yaml", memoryConfig}} {
		r := MemoryDir + "/beads/" + f.name
		if !b.assets[r] {
			b.assets[r] = true
			b.m.Assets = append(b.m.Assets, Asset{Rel: r, Data: []byte(f.data), Mode: 0o600})
		}
	}
	s.Mounts = append(s.Mounts, Mount{Source: literal(b.ws(MemoryDir, "beads")), Target: MemoryBeadsDir, Options: "ro,z"})
	script := memoryPrimeScript(mem.MemoryGuidance())
	rel := MemoryDir + "/railswitch-prime.sh"
	s.HookScripts = append(s.HookScripts, script)
	if !b.assets[rel] {
		b.assets[rel] = true
		b.m.Assets = append(b.m.Assets, Asset{Rel: rel, Data: script, Mode: 0o755})
	}
	s.Mounts = append(s.Mounts, Mount{Source: literal(b.ws(rel)), Target: MemoryPrime, Options: "ro,z"})
}

// memoryNetwork is the project's memory network: no route out, isolated
// from every other network.
func memoryNetwork(m *Model) *unit {
	u := &unit{Header: []string{markerLine(m, "")}}
	u.add("Unit", "Description", "Shared memory network of project "+m.Prefix)
	u.add("Network", "NetworkName", naming.MemoryNetwork(m.Prefix))
	u.add("Network", "Internal", "true")
	u.add("Network", "Options", "mtu=1400", "isolate=strict")
	return u
}

// memoryServer is the project's Dolt server: a data service of no
// worktree, on the memory network only, with its volume (the image's
// working dir, /var/lib/dolt, holds the databases); root without a
// password from the network (DOLT_ROOT_HOST=%), which only the project's
// agents join. Nothing is published.
func memoryServer(m *Model) *unit {
	name := naming.MemoryNetwork(m.Prefix)
	u := &unit{Header: []string{markerLine(m, ""), "# role: " + RoleData}}
	u.add("Unit", "Description", "Shared agent memory (Dolt) of project "+m.Prefix)
	const c = "Container"
	u.add(c, "Image", MemoryImage)
	u.add(c, "ContainerName", name)
	u.add(c, "Network", naming.MemoryUnit(m.Prefix)+".network:alias="+MemoryHost)
	u.add(c, "Volume", name+":/var/lib/dolt")
	u.add(c, "Environment", "DOLT_ROOT_HOST=%")
	// The server itself, under the image's tini, not the image's entrypoint:
	// that script answers SIGTERM with `kill` and `exit 1` at once, so dolt
	// got no time to close and every stop left the unit failed
	// (docker-entrypoint.sh:350). dolt sql-server creates root@%
	// from DOLT_ROOT_HOST itself (the same script, :403).
	u.add(c, "Entrypoint", "tini")
	u.add(c, "Exec", "-- dolt sql-server --host=0.0.0.0 --port="+strconv.Itoa(MemoryPort))
	u.add(c, "DropCapability", "all")
	u.add(c, "NoNewPrivileges", "true")
	u.add(c, "Memory", "1g")
	u.add(c, "PidsLimit", "512")
	u.add(c, "HealthCmd", `dolt sql -q "select 1"`)
	u.add(c, "HealthInterval", "10s")
	u.add(c, "HealthRetries", "3")
	u.add(c, "HealthStartPeriod", "60s")
	u.add(c, "Notify", "healthy")
	u.add(c, "LogDriver", "journald")
	u.add(c, "StopTimeout", strconv.Itoa(dataStopTimeout))
	u.add("Service", "Restart", "on-failure")
	u.add("Service", "RestartSec", "5")
	u.add("Service", "TimeoutStopSec", strconv.Itoa(dataStopTimeout+30))
	u.add("Service", "TimeoutStartSec", strconv.Itoa(dataStartTimeout))
	return u
}
