package render

// Shared notes (D141, D199): one folder of Markdown notes per project,
// mounted read-only into every agent of every worktree; each worktree's
// agents suggest notes in that worktree's inbox, and only the user accepts
// one into the notes (notes inbox). railswitch-notes prints what
// an agent reads at session start: the rule, then the notes' file names,
// which say what each holds. Each agent package delivers that output its own way
// (a SessionStart hook, say).
const (
	// NotesDir is the workspace folder of the shared notes.
	NotesDir = "notes"
	// NotesMount is where every agent sees NotesDir, read-only.
	NotesMount = appHome + "/notes"
	// NotesInboxDir holds <NotesInboxDir>/<slug>, a worktree's suggested
	// notes (D199): agents write it, so it is hostile.
	NotesInboxDir = ".railswitch/notes-inbox"
	// NotesInboxMount is where a worktree's agents see its inbox, writable.
	NotesInboxMount = appHome + "/notes-inbox"
	// NotesIndex is railswitch-notes in an agent.
	NotesIndex     = "/usr/local/bin/railswitch-notes"
	notesScriptRel = ".railswitch/hooks/railswitch-notes.sh"
)

// notesScript is railswitch-notes: no arguments, no network, files only.
const notesScript = `#!/bin/sh
# railswitch-notes (D141, D199): the project's shared notes for an agent's
# context at session start. Generated by railswitch.
dir="$HOME/notes"
inbox="$HOME/notes-inbox"
cat <<'RULE'
# Project notes (railswitch)

Every agent of this project, in every worktree, reads ~/notes/: one
Markdown file per note, named for what it says, words joined by
underscores (run_db_prepare_after_a_schema_change.md). The listing below is
every note, newest first. ~/notes is read-only: the human decides what goes
in it.

- Read a note (cat ~/notes/<file>) when its name is relevant to the task.
  To find notes by what they say, search them: grep -ril <word> ~/notes
- To suggest something every agent should know about this project, write
  it to ~/notes-inbox/<name>.md, named the same way. To change a note,
  write its whole new text there under the note's own name (or a new name
  if what it says has changed). The human reviews each suggestion and
  accepts or rejects it. Keep this worktree's scratch out of it.
- These are the project's memory: use them instead of your own memory
  features for anything about the project.
- Never store secrets, credentials, tokens, personal data or patient data:
  every agent reads these notes, and they stay until deleted.

RULE
# Agents write the names: ls -q turns a line break or other control
# character into "?", so a name can't forge lines of this text, and such a
# name is no file here and is skipped.
names() {
  ls -tq "$1" 2>/dev/null | while IFS= read -r f; do
    case "$f" in MEMORY.md) continue ;; *.md) ;; *) continue ;; esac
    [ -f "$1/$f" ] && printf -- '- %s\n' "$f"
  done
}
notes=$(names "$dir")
if [ -z "$notes" ]; then
  echo "(no notes yet)"
elif [ "$(printf '%s\n' "$notes" | wc -l)" -gt 200 ]; then
  printf '%s\n' "$notes" | head -n 200
  echo "- … more notes: ls -t ~/notes"
else
  printf '%s\n' "$notes"
fi
pending=$(names "$inbox" | head -n 50)
if [ -n "$pending" ]; then
  printf '\nSuggested from this worktree, not yet reviewed (~/notes-inbox):\n%s\n' "$pending"
fi
`

// The project's git config (D164): <workspace>/git/config, which the user
// writes, read-only in every container that has the worktree, as git's
// system config, so a container's own ~/.gitconfig and the repository's
// config still override it. The folder is mounted, not the file, so an
// edit (an editor's rename) shows at once.
const (
	GitDir         = "git"
	GitConfigMount = "/etc/railswitch-git"
)

// notesAgent mounts the shared notes, its worktree's inbox and
// railswitch-notes into agent s.
func (b *builder) notesAgent(s *Service) {
	if !b.assets[notesScriptRel] {
		b.assets[notesScriptRel] = true
		b.m.Assets = append(b.m.Assets, Asset{Rel: notesScriptRel, Data: []byte(notesScript), Mode: 0o755})
	}
	s.Mounts = append(s.Mounts,
		Mount{Source: literal(b.ws(NotesDir)), Target: NotesMount, Options: "ro,z"},
		Mount{Source: "{notes.inbox}", Target: NotesInboxMount, Options: "rw,z"},
		Mount{Source: literal(b.ws(notesScriptRel)), Target: NotesIndex, Options: "ro,z"})
}
