package render

// Shared notes (D141): one folder of Markdown notes per project, mounted
// writable into every agent of every worktree. railswitch-notes prints what
// an agent reads at session start: the rule, then one line per note (its
// file and first line). Each agent package delivers that output its own way
// (a SessionStart hook, say).
const (
	// NotesDir is the workspace folder of the shared notes.
	NotesDir = "notes"
	// NotesMount is where every agent sees NotesDir.
	NotesMount = appHome + "/notes"
	// NotesIndex is railswitch-notes in an agent.
	NotesIndex     = "/usr/local/bin/railswitch-notes"
	notesScriptRel = ".railswitch/hooks/railswitch-notes.sh"
)

// notesScript is railswitch-notes: no arguments, no network, files only.
const notesScript = `#!/bin/sh
# railswitch-notes (D141): the project's shared notes for an agent's
# context at session start. Generated by railswitch.
dir="$HOME/notes"
cat <<'RULE'
# Project notes (railswitch)

Every agent of this project, in every worktree, shares ~/notes/: one
Markdown file per note, first line "# <one-line summary>", then the details.
Below is one line per note (file, summary), newest first.

- Read a note (cat ~/notes/<file>) when its summary is relevant to the task.
- To remember something every agent should know about this project, write
  it there as a note (a short kebab-case file name ending in .md). Update an
  existing note on the same subject instead of adding another. Keep this
  worktree's scratch out of it.
- These are the project's memory: use them instead of your own memory
  features for anything about the project.
- Never store secrets, credentials, tokens, personal data or patient data:
  every agent reads these notes, and they stay until deleted.

RULE
n=0
ls -t "$dir" 2>/dev/null | while IFS= read -r f; do
  case "$f" in MEMORY.md) continue ;; *.md) ;; *) continue ;; esac
  [ -f "$dir/$f" ] || continue
  n=$((n + 1))
  if [ "$n" -gt 200 ]; then
    echo "- … more notes: ls -t ~/notes"
    break
  fi
  # A note's summary is its first line; a memory file copied in from an
  # agent's own memory starts with front matter: its description, else name.
  title=$(head -n 1 "$dir/$f")
  if [ "$title" = "---" ]; then
    title=$(sed -n '2,/^---$/s/^description: *//p' "$dir/$f" | head -n 1)
    [ -n "$title" ] || title=$(sed -n '2,/^---$/s/^name: *//p' "$dir/$f" | head -n 1)
  fi
  title=$(printf '%s' "$title" | sed 's/^#* *//' | cut -c1-150)
  printf -- '- %s: %s\n' "$f" "$title"
done
[ -n "$(ls "$dir" 2>/dev/null)" ] || echo "(no notes yet)"
`

// notesAgent mounts the shared notes and railswitch-notes into agent s.
func (b *builder) notesAgent(s *Service) {
	if !b.assets[notesScriptRel] {
		b.assets[notesScriptRel] = true
		b.m.Assets = append(b.m.Assets, Asset{Rel: notesScriptRel, Data: []byte(notesScript), Mode: 0o755})
	}
	s.Mounts = append(s.Mounts,
		Mount{Source: literal(b.ws(NotesDir)), Target: NotesMount, Options: "z"},
		Mount{Source: literal(b.ws(notesScriptRel)), Target: NotesIndex, Options: "ro,z"})
}
